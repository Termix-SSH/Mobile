// Turns drizzle-kit's SQL files into src/core/db/migrations.ts, so the app
// bundles them as plain strings. Run with `npm run db:generate`.
const fs = require("node:fs");
const path = require("node:path");
const { execSync } = require("node:child_process");

const root = path.join(__dirname, "..");
const outFile = path.join(root, "src/core/db/migrations.ts");

/** The migrations drizzle-kit wrote, in order. */
function readMigrations(dir = path.join(root, "drizzle")) {
  const journal = JSON.parse(
    fs.readFileSync(path.join(dir, "meta/_journal.json"), "utf8"),
  );
  return journal.entries.map((entry) => ({
    version: entry.idx + 1,
    name: entry.tag,
    sql: fs.readFileSync(path.join(dir, `${entry.tag}.sql`), "utf8"),
  }));
}

function buildModule(migrations) {
  return [
    "// Generated by scripts/db-migrations.cjs from drizzle/. Do not edit.",
    "",
    "export interface Migration {",
    "  version: number;",
    "  name: string;",
    "  sql: string;",
    "}",
    "",
    `export const migrations: Migration[] = ${JSON.stringify(migrations, null, 2)};`,
    "",
  ].join("\n");
}

if (require.main === module) {
  const name = process.argv[2];
  execSync(
    `npx drizzle-kit generate --config drizzle.config.ts${name ? ` --name ${name}` : ""}`,
    { cwd: root, stdio: "inherit" },
  );
  fs.writeFileSync(outFile, buildModule(readMigrations()));
  execSync(`npx prettier --write "${outFile}"`, {
    cwd: root,
    stdio: "inherit",
  });
}

module.exports = { readMigrations, buildModule };
